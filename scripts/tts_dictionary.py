_INT_TO_KANA = {
    0: "ゼロ", 1: "いち", 2: "に", 3: "さん", 4: "よん", 5: "ご",
    6: "ろく", 7: "なな", 8: "はち", 9: "きゅう", 10: "じゅう",
}

_LETTER_TO_KATAKANA = {
    "A": "エー", "B": "ビー", "C": "シー", "D": "ディー", "E": "イー",
    "F": "エフ", "G": "ジー", "H": "エイチ", "I": "アイ", "J": "ジェイ",
    "K": "ケー", "L": "エル", "M": "エム", "N": "エヌ", "O": "オー",
    "P": "ピー", "Q": "キュー", "R": "アール", "S": "エス", "T": "ティー",
    "U": "ユー", "V": "ブイ", "W": "ダブリュー", "X": "エックス", "Y": "ワイ", "Z": "ゼット",
}


def int_to_japanese_reading(n: int) -> str:
    if n < 0:
        return "マイナス" + int_to_japanese_reading(-n)
    if n == 0:
        return "ゼロ"
    parts: list[str] = []
    if n >= 10000:
        man = n // 10000
        n %= 10000
        parts.append((int_to_japanese_reading(man) if man > 1 else "いち") + "まん")
    if n >= 1000:
        sen = n // 1000
        n %= 1000
        if sen == 1:
            parts.append("せん")
        elif sen == 3:
            parts.append("さんぜん")
        elif sen == 8:
            parts.append("はっせん")
        else:
            parts.append(_INT_TO_KANA[sen] + "せん")
    if n >= 100:
        hyaku = n // 100
        n %= 100
        if hyaku == 1:
            parts.append("ひゃく")
        elif hyaku == 3:
            parts.append("さんびゃく")
        elif hyaku == 6:
            parts.append("ろっぴゃく")
        elif hyaku == 8:
            parts.append("はっぴゃく")
        else:
            parts.append(_INT_TO_KANA[hyaku] + "ひゃく")
    if n >= 10:
        ju = n // 10
        n %= 10
        parts.append(("じゅう" if ju == 1 else _INT_TO_KANA[ju] + "じゅう"))
    if n > 0:
        parts.append(_INT_TO_KANA[n])
    return "".join(parts)


_MISSING_PERIOD_PATTERNS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"(できる|わかる|られる|れます|きます|します|あります|ません)(今日は|今回は|ここでは|まずは|それでは|つぎに|次に)"), r"\1。\2"),
    (re.compile(r"(ことを一つ|ことをひとつ)(教材の|まずは|今回は|今日は)"), r"\1。\2"),
]


_KANJI_OR_ALNUM_RE = re.compile(r"[一-龥々〆ヵヶA-Za-z0-9]")


def _kata_to_hira(s: str) -> str:
    return "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in s)


def _is_ascii_alnum(ch: str) -> bool:
    return ch.isascii() and ch.isalnum()


def _segment_with_dictionary_and_hiragana_instruction(
    text: str,
    custom_dict: Optional[dict[str, str]] = None,
    hiragana_instruction: Optional[str] = None,
) -> tuple[str, str, list[tuple[str, str]]]:
    """
    Core Hybrid Resolution Engine (v3.6):
    1. PRIORITY 1 (`CUSTOM` & `ACTIVE_DICT` — 12,180+ entries):
       - User custom overrides + English/AI/IT terms (Katakana), counters, dates, homographs, tricky Kanji.
    2. PRIORITY 2 (`REF_DICT` — 4,400+ entries):
       - Verified modern Japanese Kanji compounds & verb/adjective conjugations.
       - Keeps verified Kanji intact in `prosody_text` for natural pitch accent, while using the dictionary's
         exact Hiragana reading in `kana_text` and as an alignment anchor.
    3. PRIORITY 3 (`OOV` Fallback -> `hiragana_instruction` [`narration_tts` / `narration_kana`]):
       - Any Kanji or English/number token NOT in the dictionary (`OOV`) automatically extracts its reading
         from the scene's Hiragana text instruction (`hiragana_instruction`) via sequence alignment anchored
         by the surrounding dictionary & Kana tokens!
    Returns `(prosody_text, kana_text, applied_replacements)`.
    """
    import difflib

    active_by_first, ref_by_first = _get_indexed_builtin_dicts()
    custom_by_first: dict[str, list[tuple[str, str]]] = {}
    if custom_dict:
        for k, v in custom_dict.items():
            if k and v:
                custom_by_first.setdefault(k[0], []).append((k, v))
        for ch in custom_by_first:
            custom_by_first[ch].sort(key=lambda kv: len(kv[0]), reverse=True)

    n = len(text)
    i = 0
    tokens: list[list[str]] = []  # [kind, surface, prosody_val, hira_val]
    applied: list[tuple[str, str]] = []

    def _match_at(pos: int) -> Optional[tuple[str, str, str, str]]:
        ch = text[pos]
        for k, v in custom_by_first.get(ch, ()):
            if text.startswith(k, pos):
                if k.isascii() and k.isalpha():
                    if pos > 0 and _is_ascii_alnum(text[pos - 1]):
                        continue
                    end = pos + len(k)
                    if end < n and _is_ascii_alnum(text[end]):
                        continue
                return ("CUSTOM", k, v, _kata_to_hira(v))
        for k, v in active_by_first.get(ch, ()):
            if text.startswith(k, pos):
                if k.isascii() and k.isalpha():
                    if pos > 0 and _is_ascii_alnum(text[pos - 1]):
                        continue
                    end = pos + len(k)
                    if end < n and _is_ascii_alnum(text[end]):
                        continue
                return ("ACTIVE", k, v, _kata_to_hira(v))
        for k, v in ref_by_first.get(ch, ()):
            if text.startswith(k, pos):
                return ("REF", k, k, _kata_to_hira(v))
        return None

    while i < n:
        m = _match_at(i)
        if m is not None:
            tokens.append(list(m))
            if m[0] in ("CUSTOM", "ACTIVE") and m[1] != m[2] and (m[1], m[2]) not in applied:
                applied.append((m[1], m[2]))
            i += len(m[1])
            continue
        if not _KANJI_OR_ALNUM_RE.match(text[i]):
            start = i
            while i < n and not _KANJI_OR_ALNUM_RE.match(text[i]) and _match_at(i) is None:
                i += 1
            surf = text[start:i]
            tokens.append(["KANA", surf, surf, _kata_to_hira(surf)])
        else:
            start = i
            while i < n and _KANJI_OR_ALNUM_RE.match(text[i]) and _match_at(i) is None:
                i += 1
            surf = text[start:i]
            tokens.append(["OOV", surf, surf, surf])

    # Priority 3: Resolve any Out-Of-Vocabulary (OOV) tokens using `hiragana_instruction` (`narration_tts`)!
    has_oov = any(tok[0] == "OOV" for tok in tokens)
    if has_oov and hiragana_instruction and hiragana_instruction.strip():
        clean_inst = re.sub(r"[\s　]+", "", _kata_to_hira(hiragana_instruction.strip()))
        src_hira_parts: list[str] = []
        token_spans: list[tuple[int, int]] = []
        cur = 0
        for tok in tokens:
            h = re.sub(r"[\s　]+", "", tok[3])
            src_hira_parts.append(h)
            token_spans.append((cur, cur + len(h)))
            cur += len(h)
        src_full = "".join(src_hira_parts)
        sm = difflib.SequenceMatcher(None, src_full, clean_inst, autojunk=False)
        blocks = sm.get_matching_blocks()
        for idx, tok in enumerate(tokens):
            if tok[0] != "OOV":
                continue
            s_start, s_end = token_spans[idx]
            inst_start = 0
            for a, b, size in blocks:
                if size == 0:
                    continue
                if a + size <= s_start:
                    inst_start = max(inst_start, b + size)
                elif a < s_start < a + size:
                    inst_start = max(inst_start, b + (s_start - a))
            inst_end = len(clean_inst)
            for a, b, size in blocks:
                if size == 0:
                    continue
                if a >= s_end:
                    inst_end = min(inst_end, b)
                    break
                elif a < s_end < a + size:
                    inst_end = min(inst_end, b + (s_end - a))
                    break
            if 0 <= inst_start < inst_end <= len(clean_inst):
                extracted = clean_inst[inst_start:inst_end].strip("、。！？「」『』（）()・")
                if extracted and len(extracted) <= max(len(tok[1]) * 8, 24):
                    tok[2] = extracted
                    tok[3] = extracted
                    applied.append((tok[1], f"{extracted} [ひらがな指示]"))

    prosody_out = "".join(tok[2] for tok in tokens)
    kana_out = "".join(tok[3] for tok in tokens)
    return prosody_out, kana_out, applied


def normalize_prosody_Japanese_tts(
    text: str,
    custom_dict: Optional[dict[str, str]] = None,
    hiragana_instruction: Optional[str] = None,
) -> tuple[str, list[tuple[str, str]]]:
    """
    Prosody-Preserving Japanese TTS Normalizer (v3.6 — Dictionary Priority + Hiragana Instruction Fallback):
    1. Prioritizes the 16,563-entry Built-in Dictionary + user `custom_dict`:
       - English / AI / IT / SaaS / Programming terms -> Katakana (`active_prosody_readings`).
       - Counters / dates / times / homographs / tricky Kanji -> Exact Japanese readings (`active_prosody_readings`).
       - Verified modern Japanese Kanji compounds (`reference_kanji_readings`) -> Kept in Kanji for natural pitch accent.
    2. For ANY word or character NOT in the dictionary (`OOV`), falls back to the scene's Hiragana text
       instruction (`hiragana_instruction` = `narration_tts` / `narration_kana`), then regex number/acronym rules.
    Returns `(normalized_text, applied_replacements_list)`.
    """
    t = text.strip()
    if not t:
        return "", []

    # 1. Strip [ ] / ［ ］ bracket tags
    t = re.sub(
        r"(^|[。！？、「『\s])(?:\[[^\]]*\]|［[^］]*］)(?:で使った|で作った|で学んだ|の|で|では|とは|から|へ|に|を|が|は)?\s*",
        r"\1",
        t,
    )
    t = re.sub(r"(?:\[[^\]]*\]|［[^］]*］)の", "", t)
    t = re.sub(r"\[[^\]]*\]|［[^］]*］", "", t)

    # 2. Repair missing periods in concatenated bullet/paragraph sentences
    for pat, repl in _MISSING_PERIOD_PATTERNS:
        t = pat.sub(repl, t)

    # 3. Segment with Dictionary Priority + Hiragana Text Instruction (`narration_tts`) Fallback for OOV tokens
    t, _kana_out, applied = _segment_with_dictionary_and_hiragana_instruction(
        t, custom_dict=custom_dict, hiragana_instruction=hiragana_instruction
    )

    # 4. Regex fallback for remaining number ranges like `1〜3`, `2~4`
    t = re.sub(
        r"(\d+)\s*[〜~～\-－]\s*(\d+)",
        lambda m: f"{int_to_japanese_reading(int(m.group(1)))}から{int_to_japanese_reading(int(m.group(2)))}",
        t,
    )

    # 5. Regex fallback for remaining standalone uppercase English acronyms (2-5 letters) -> Katakana
    def _acronym_repl(m: re.Match[str]) -> str:
        word = m.group(0)
        kata = "".join(_LETTER_TO_KATAKANA.get(ch, ch) for ch in word)
        applied.append((word, kata))
        return kata

    t = re.sub(r"(?<![A-Za-z])[A-Z]{2,5}(?![A-Za-z])", _acronym_repl, t)

    # 6. Punctuation & symbol prosody cleanup
    t = t.replace("→", "、つぎに、")
    t = re.sub(r"・+", "、", t)
    t = re.sub(r"、{2,}", "、", t)
    t = re.sub(r"[ \t]+", " ", t)
    return t.strip(), applied


